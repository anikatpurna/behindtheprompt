import { useState } from 'react';
import { AlertTriangle, ChevronDown, Compass, Cpu, Lightbulb, Rocket, SearchX } from 'lucide-react';
import { Card, EmptyState, SectionHeader, cx } from './ui.jsx';

const TYPES = {
  risk: { label: 'Risk', icon: AlertTriangle, chip: 'bg-red-50 text-red-700', icon_: 'bg-red-50 text-red-600', bar: 'bg-bad' },
  opportunity: { label: 'Opportunity', icon: Rocket, chip: 'bg-green-50 text-green-700', icon_: 'bg-green-50 text-green-600', bar: 'bg-ok' },
  info: { label: 'Observation', icon: Compass, chip: 'bg-blue-50 text-blue-700', icon_: 'bg-blue-50 text-blue-500', bar: 'bg-softblue' },
};

const RULES = [
  'Portfolio margin (total profit ÷ total revenue) compared with the target margin.',
  'Customer with the lowest gross margin; customers strictly below the target.',
  'Customer contributing the largest monthly gross profit and its share of the portfolio.',
  'Cost headroom: revenue ÷ cost − 1 gives the cost increase each customer can absorb before break-even. Also tests a 15% cost increase.',
  'Customers with less than 5% cost headroom above the target margin.',
  'Labor hours per 1,000 units and cost per unit (only when those columns exist).',
  'Quote automation capacity from the Efficiency & ROI assumptions (hypothetical).',
];

export default function Insights({ insights, target }) {
  const [filter, setFilter] = useState('all');
  const [open, setOpen] = useState(false);
  const shown = insights.filter((i) => filter === 'all' || i.type === filter);
  const count = (t) => insights.filter((i) => i.type === t).length;

  return (
    <div className="space-y-6">
      <SectionHeader
        eyebrow="Decision support"
        title="Executive Insights"
        subtitle="Findings generated by fixed business rules applied to the numbers in this dashboard. Each one shows its evidence."
        right={
          <span className="inline-flex items-center gap-2 rounded-full border border-slate-200 bg-white px-3 py-1.5 text-xs font-semibold text-slate-600 shadow-sm">
            <Cpu size={14} className="text-teal" /> Rules-based analysis · not a live AI model
          </span>
        }
      />

      <div className="flex flex-wrap gap-2" role="group" aria-label="Filter insights">
        {[['all', 'All', insights.length], ['risk', 'Risks', count('risk')], ['opportunity', 'Opportunities', count('opportunity')], ['info', 'Observations', count('info')]].map(([k, label, n]) => (
          <button key={k} onClick={() => setFilter(k)} aria-pressed={filter === k}
            className={cx('inline-flex items-center gap-2 rounded-full border px-3.5 py-1.5 text-sm font-medium transition', filter === k ? 'border-navy bg-navy text-white' : 'border-slate-200 bg-white text-slate-600 hover:border-slate-300')}>
            {label}<span className={cx('rounded-full px-1.5 text-xs tabular', filter === k ? 'bg-white/20' : 'bg-slate-100 text-slate-500')}>{n}</span>
          </button>
        ))}
      </div>

      {shown.length === 0 ? (
        <EmptyState icon={SearchX} title="Nothing in this category" body={`No ${filter} insights were triggered at the current ${Math.round(target * 100)}% target margin.`} />
      ) : (
        <div className="grid gap-4 lg:grid-cols-2">
          {shown.map((i, idx) => {
            const t = TYPES[i.type];
            const Icon = t.icon;
            return (
              <Card key={i.id} className="relative animate-fadeUp overflow-hidden p-5 sm:p-6" style={{ animationDelay: `${idx * 40}ms` }}>
                <span className={cx('absolute inset-y-0 left-0 w-1', t.bar)} />
                <div className="flex items-start gap-3">
                  <span className={cx('grid h-9 w-9 shrink-0 place-items-center rounded-xl', t.icon_)}><Icon size={18} /></span>
                  <div className="min-w-0">
                    <span className={cx('rounded-full px-2 py-0.5 text-[11px] font-bold uppercase tracking-wide', t.chip)}>{t.label}</span>
                    <h3 className="mt-2 text-[15px] font-semibold leading-snug text-navy">{i.title}</h3>
                    <p className="mt-1.5 text-sm leading-relaxed text-slate-600">{i.detail}</p>
                  </div>
                </div>
                <div className="mt-4 rounded-xl bg-mist px-3.5 py-2.5 text-xs text-slate-500">
                  <span className="font-semibold text-slate-600">Evidence · </span>
                  <span className="tabular">{i.evidence}</span>
                </div>
                <div className="mt-2 flex gap-2 rounded-xl bg-teal-50 px-3.5 py-2.5 text-sm text-teal-900">
                  <Lightbulb size={16} className="mt-0.5 shrink-0 text-teal-600" />
                  <span><span className="font-semibold">Possible action: </span>{i.action}</span>
                </div>
              </Card>
            );
          })}
        </div>
      )}

      <p className="text-xs leading-relaxed text-slate-500">
        Actions are suggestions for management to consider, not automatic decisions. Insights recalculate whenever the data or target margin changes.
      </p>

      <Card>
        <button onClick={() => setOpen((o) => !o)} aria-expanded={open} className="flex w-full items-center justify-between px-5 py-4 text-left text-sm font-semibold text-navy">
          How these insights are generated
          <ChevronDown size={18} className={cx('text-slate-400 transition', open && 'rotate-180')} />
        </button>
        {open && (
          <ul className="list-disc space-y-1.5 px-9 pb-5 text-sm text-slate-600">
            {RULES.map((r) => <li key={r}>{r}</li>)}
          </ul>
        )}
      </Card>
    </div>
  );
}
